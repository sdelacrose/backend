"""GED-L1.3: protection and uniqueness of the official document reference (full_document_number).

Numbering perimeter (project_management.services.document_numbering): one sequence counter per
library owner -- project, company or freelancer -- and per sequence scope. There is no database
constraint on the reference itself; these tests cover the application-level protections.
"""
import threading
from types import SimpleNamespace

from django.db import OperationalError, connection, transaction
from django.test import TransactionTestCase

from models.models import CompanyProfile, User
from project_management.models import Document, DocumentReferenceCounter, ECPMPConfig, Folder
from project_management.services.document_bulk_update import BulkDocumentUpdateRequestSerializer
from project_management.services.document_numbering import lock_reference_perimeter
from project_management.services.document_reference import generate_document_reference
from project_management.test_document_control_reference import ProjectFixtureMixin
from project_management.test_document_type_lock import DocumentTypeLockTests
from project_management.test_document_workflow import WorkflowTestBase

REFUSED = "The official document reference is generated by LINKS and cannot be edited"


class ReferenceProtectionTests(ProjectFixtureMixin, WorkflowTestBase):
    def setUp(self):
        super().setUp()
        self.project, self.folder = self.make_project("Marseille Office Renovation")
        self.project.project_code = "MRS"
        self.project.save()

    unreferenced = DocumentTypeLockTests.unreferenced
    attempt = DocumentTypeLockTests.attempt
    api_patch = DocumentTypeLockTests.api_patch

    # -- generation ---------------------------------------------------------------------------

    def test_creation_generates_the_reference_automatically(self):
        document = self.create_doc(self.folder)
        self.assertEqual((document.sequence_number, document.full_document_number),
                         (1, "MRS-STR-DWG-00001"))
        second = self.create_doc(self.folder)
        self.assertEqual(second.full_document_number, "MRS-STR-DWG-00002")

    def test_a_reference_sent_at_creation_is_ignored(self):
        document = self.create_doc(self.folder, full_document_number="HACK-0001")
        self.assertEqual(document.full_document_number, "MRS-STR-DWG-00001")

    def test_a_new_document_never_receives_an_existing_reference_even_across_counters(self):
        # discipline-scoped counters + a reference format without the discipline: the first
        # document of each discipline would both be "MRS-00001" -- the generator must not reuse it
        ECPMPConfig.objects.filter(project=self.project).update(document_control_configuration={
            "reference": {"segments": ["PROJECT", "SEQUENCE"], "sequence_scope": "DISCIPLINE"}})
        first = self.create_doc(self.folder, discipline="Structure")
        second = self.create_doc(self.folder, discipline="Electrical")
        self.assertEqual(first.full_document_number, "MRS-00001")
        self.assertNotEqual(second.full_document_number, first.full_document_number)
        references = list(Document.objects.filter(folder=self.folder).values_list(
            "full_document_number", flat=True))
        self.assertEqual(len(references), len(set(references)))

    # -- editing: single and API --------------------------------------------------------------

    def test_changing_the_reference_is_refused_with_a_business_message(self):
        document = self.create_doc(self.folder)
        serializer, valid = self.attempt(document, full_document_number="HACK-0001")
        self.assertFalse(valid)
        self.assertIn(REFUSED, str(serializer.errors["full_document_number"][0]))
        self.assertEqual(Document.objects.get(pk=document.pk).full_document_number,
                         "MRS-STR-DWG-00001")

    def test_clearing_the_reference_is_refused_too(self):
        document = self.create_doc(self.folder)
        for cleared in ("", None, "   "):
            with self.subTest(cleared=cleared):
                serializer, valid = self.attempt(document, full_document_number=cleared)
                self.assertFalse(valid)
                self.assertIn(REFUSED, str(serializer.errors["full_document_number"][0]))
        self.assertEqual(Document.objects.get(pk=document.pk).full_document_number,
                         "MRS-STR-DWG-00001")

    def test_a_direct_api_call_cannot_change_or_clear_the_reference(self):
        document = self.create_doc(self.folder)
        for value in ("HACK-0001", "", None):
            with self.subTest(value=value):
                response = self.api_patch(document, {"full_document_number": value})
                self.assertEqual(response.status_code, 400, response.data)
                self.assertIn(REFUSED, str(response.data["full_document_number"][0]))
        self.assertEqual(Document.objects.get(pk=document.pk).full_document_number,
                         "MRS-STR-DWG-00001")

    def test_a_form_echoing_the_stored_reference_and_other_fields_still_work(self):
        document = self.create_doc(self.folder)
        response = self.api_patch(
            document, {"full_document_number": document.full_document_number, "status": "Issued"})
        self.assertEqual(response.status_code, 200, getattr(response, "data", None))
        stored = Document.objects.get(pk=document.pk)
        self.assertEqual((stored.status, stored.full_document_number), ("Issued", "MRS-STR-DWG-00001"))
        self.assertEqual(self.api_patch(document, {"status": "Approved"}).status_code, 200)

    def test_a_document_without_reference_cannot_be_given_one_by_hand(self):
        free = self.unreferenced()
        self.assertFalse(free.full_document_number)
        _, valid = self.attempt(free, full_document_number="HACK-0001")
        self.assertFalse(valid)
        self.assertEqual(self.api_patch(free, {"full_document_number": ""}).status_code, 200)
        self.assertEqual(self.api_patch(free, {"status": "Issued"}).status_code, 200)
        self.assertFalse(Document.objects.get(pk=free.pk).full_document_number)

    # -- bulk update --------------------------------------------------------------------------

    def test_bulk_update_cannot_carry_a_reference(self):
        for field in ("full_document_number", "sequence_number"):
            with self.subTest(field=field):
                request = BulkDocumentUpdateRequestSerializer(
                    data={"ids": [1], "changes": {field: "X"}})
                self.assertFalse(request.is_valid())
                self.assertIn(field, str(request.errors["changes"]))

    # -- the locks of GED-L1.1 / L1.2 stay in place -------------------------------------------

    def test_the_type_and_discipline_locks_are_still_operational(self):
        document = self.create_doc(self.folder)
        for data, field in (({"document_type": "Report"}, "document_type"),
                            ({"discipline": "Electrical"}, "discipline")):
            serializer, valid = self.attempt(document, **data)
            self.assertFalse(valid)
            self.assertIn(field, serializer.errors)

    def test_a_refused_edit_leaves_revisions_and_history_alone(self):
        document = self.create_doc(self.folder)
        history = Document.history.filter(id=document.id).count()
        revisions = document.revisions.count()
        self.attempt(document, full_document_number="HACK-0001")
        self.assertEqual(Document.history.filter(id=document.id).count(), history)
        self.assertEqual(document.revisions.count(), revisions)


def _make_library(label):
    user = User.objects.create_user(
        email=f"{label}@links-local.invalid", first_name="C", last_name="C", title="Mr",
        user_type="company_user")
    company = CompanyProfile.objects.create(
        admin_user=user, company_name=f"{label} Company", company_address="1", post_code="0",
        company_town="T", company_country="C", company_tell_no="0", company_mob_no="1",
        company_web_address="http://x", company_email_address=f"{label}@x.invalid",
        company_tax_reference="T", company_iban="I")
    return Folder.objects.create(company_profile=company, name=f"{label} folder")


class ReferencePerimeterConcurrencyTests(TransactionTestCase):
    """Real threads, real connections (TransactionTestCase): the perimeter lock and the creation
    of references under concurrency."""

    # discipline-scoped counters and a format without the discipline: two parallel creations of
    # the same library would both build "<COMPANY>-00001" from two different counter rows
    CONFIG = SimpleNamespace(document_control_configuration={
        "reference": {"segments": ["COMPANY", "SEQUENCE"], "sequence_scope": "DISCIPLINE"}})

    def test_parallel_creations_of_one_library_never_share_a_reference(self):
        folder = _make_library("par")
        references, errors = [], []

        def worker(code):
            try:
                with transaction.atomic():
                    sequence, reference = generate_document_reference(
                        folder, document_type="Drawing", discipline="", discipline_code=code,
                        category=None, config=self.CONFIG)
                    Document.objects.create(folder=folder, file_name="x.txt",
                                            sequence_number=sequence, full_document_number=reference)
                references.append(reference)
            except Exception as error:  # pragma: no cover
                errors.append(error)
            finally:
                connection.close()

        threads = [threading.Thread(target=worker, args=(code,))
                   for code in ("STR", "ELE", "CIV", "MEC", "STR", "ELE", "CIV", "MEC")]
        [t.start() for t in threads]
        [t.join() for t in threads]
        self.assertEqual(errors, [])
        self.assertEqual(len(references), 8)
        self.assertEqual(len(set(references)), 8, references)
        stored = list(Document.objects.filter(folder=folder).values_list(
            "full_document_number", flat=True))
        self.assertEqual(len(stored), len(set(stored)))
        self.assertGreaterEqual(DocumentReferenceCounter.objects.count(), 4)

    def test_the_perimeter_lock_blocks_the_same_library_and_only_that_one(self):
        mine, other = _make_library("mine"), _make_library("other")
        held, release = threading.Event(), threading.Event()
        problems = []

        def holder():
            try:
                with transaction.atomic():
                    lock_reference_perimeter(mine)
                    held.set()
                    release.wait(15)
            except Exception as error:  # pragma: no cover
                problems.append(error)
                held.set()
            finally:
                connection.close()

        thread = threading.Thread(target=holder)
        thread.start()
        self.assertTrue(held.wait(15))

        def try_lock(folder):
            with transaction.atomic():
                with connection.cursor() as cursor:
                    cursor.execute("SET LOCAL lock_timeout = '300ms'")
                lock_reference_perimeter(folder)

        try:
            with self.assertRaises(OperationalError):
                try_lock(mine)              # same perimeter: waits for the holder
            try_lock(other)                 # another perimeter: not blocked
        finally:
            release.set()
            thread.join()
        self.assertEqual(problems, [])
        try_lock(mine)                      # released at the end of the holder's transaction
